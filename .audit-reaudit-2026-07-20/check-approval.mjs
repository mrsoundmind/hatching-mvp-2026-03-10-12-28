console.log('HIGHRISK_TASK:', JSON.stringify(t.rows.map(r=>({title:r.title.slice(0,50), status:r.status, awaitingApproval:r.metadata?.awaitingApproval, hasDraft: !!r.metadata?.draftOutput}))));
